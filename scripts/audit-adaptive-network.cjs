const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const source=fs.readFileSync('game/assets/combat.js','utf8');
const start=source.indexOf('function createNetworkTiming(){'),end=source.indexOf('// End adaptive display timing.');
assert(start>=0&&end>start);
const timing=vm.runInNewContext(source.slice(start,end)+'\nnetworkTiming;');
let remote=0,local=5000;
const tick=jitter=>{remote+=1000/30;local+=1000/30+jitter;timing.observe(local,remote);};
for(let i=0;i<120;i++)tick(0);
assert(timing.delay>=32&&timing.delay<45,'A stable 30 Hz connection does not pay the old 80 ms buffer');
const stable=timing.delay;
for(let i=0;i<18;i++)tick(i%2?0:70);
assert(timing.delay>stable+15&&timing.delay<=100,'Jitter increases the buffer within its limit');
for(let i=0;i<200;i++)tick(0);
assert(timing.delay<45,'A recovered connection returns to low delay');
const before=timing.delay;timing.observe(local+50,remote-20);
assert.equal(timing.delay,before,'A stale timestamp cannot change the clock');
timing.observe(NaN,Infinity);assert.equal(timing.delay,before);
timing.reset();assert.equal(timing.delay,50,'A new room does not inherit old jitter');
assert.equal(timing.jitter,0);
console.log('PASS adaptive network timing: stable <45 ms, jitter protection <=100 ms, recovery and room reset');
